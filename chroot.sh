#!/usr/bin/env bash
# chroot.sh - runs INSIDE the new system (started by install.sh, reads /root/install.conf)
set -euo pipefail

has()  { [[ " ${FEATS:-} " == *" $1 "* ]]; }
log()  { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33mWARN:\033[0m %s\n' "$*"; }

svc() {  # svc <service> [openrc-runlevel]
  if [[ $INIT == systemd ]]; then systemctl enable "$1"; else rc-update add "$1" "${2:-default}"; fi
}

derive_profile() {  # <current-profile> <de> <init>  ->  profile to use
  local base=${1%/systemd} sub="" new
  case $2 in gnome) sub=gnome ;; kde) sub=plasma ;; esac
  new=$base${sub:+/$sub}
  if [[ $3 == systemd ]]; then new+=/systemd; fi
  echo "$new"
}

binhost_version() {  # <profile> -> e.g. 23.0
  local v; v=$(sed -nE 's#.*/amd64/([0-9]+\.[0-9]+).*#\1#p' <<<"$1")
  echo "${v:-23.0}"
}

xkb_layout() {  # console keymap -> XKB layout
  case $1 in uk) echo gb ;; *) echo "${1%%-*}" ;; esac
}

accept_config_updates() {  # fresh install: take every pending ._cfgNNNN_ file
  local root=${1:-/etc} f
  while IFS= read -r -d '' f; do
    mv -f "$f" "$(dirname "$f")/$(basename "$f" | sed -E 's/^\._cfg[0-9]{4}_//')"
  done < <(find "$root" -name '._cfg[0-9][0-9][0-9][0-9]_*' -print0 | sort -z)
}

write_make_conf() {
  local cf="-O2 -pipe" use="networkmanager" vc="" gp
  if [[ $BINHOST == x86-64-v3 ]]; then cf+=" -march=x86-64-v3"; fi
  if has audio;     then use+=" pipewire pulseaudio"; fi
  if has bluetooth; then use+=" bluetooth"; fi
  if has wifi;      then use+=" wifi"; fi
  if has printing;  then use+=" cups"; fi
  if [[ $DE != none ]]; then use+=" X"; fi
  if [[ $INIT == openrc ]]; then use+=" elogind -systemd"; else use+=" systemd"; fi
  case $GPU in
    all)     vc="intel amdgpu radeonsi nouveau" ;;
    intel)   vc="intel" ;;
    amd)     vc="amdgpu radeonsi" ;;
    nouveau) vc="nouveau" ;;
    vm)      vc="virgl vmware" ;;
  esac
  if [[ $BOOT_MODE == uefi ]]; then gp="efi-64"; else gp="pc"; fi

  cat > /etc/portage/make.conf <<MAKECONF
# Generated by gentoo-install. Generic flags on purpose: the binhost stays usable.
COMMON_FLAGS="$cf"
CFLAGS="\${COMMON_FLAGS}"
CXXFLAGS="\${COMMON_FLAGS}"
FCFLAGS="\${COMMON_FLAGS}"
FFLAGS="\${COMMON_FLAGS}"
MAKEOPTS="-j$JOBS"
LC_MESSAGES=C.utf8
ACCEPT_LICENSE="-* @FREE @BINARY-REDISTRIBUTABLE"
USE="$use"
INPUT_DEVICES="libinput"
VIDEO_CARDS="$vc"
GRUB_PLATFORMS="$gp"
FEATURES="getbinpkg binpkg-request-signature"
EMERGE_DEFAULT_OPTS="--getbinpkg --binpkg-respect-use=y --jobs=2 --autounmask-continue=y --autounmask-keep-keywords=y"
MAKECONF

  mkdir -p /etc/portage/package.use
  {
    echo "sys-kernel/installkernel grub dracut"
    if has wifi; then echo "net-misc/networkmanager wifi"; else echo "net-misc/networkmanager -wifi"; fi
    if has bluetooth; then echo "net-misc/networkmanager bluetooth"; fi
    if has audio; then echo "media-video/pipewire sound-server"; fi
    if has audio && has bluetooth; then echo "media-video/pipewire bluetooth"; fi
  } > /etc/portage/package.use/gentoo-install
}

setup_binhost() {
  local profile ver
  profile=$(eselect profile show | tail -n1 | xargs)
  ver=$(binhost_version "$profile")
  mkdir -p /etc/portage/binrepos.conf
  cat > /etc/portage/binrepos.conf/gentoobinhost.conf <<BINHOST_CONF
[gentoobinhost]
priority = 1
sync-uri = https://distfiles.gentoo.org/releases/amd64/binpackages/$ver/$BINHOST/
BINHOST_CONF
  log "Binhost: $ver/$BINHOST"
}

set_profile() {
  local cur new
  cur=$(eselect profile show | tail -n1 | xargs)
  new=$(derive_profile "$cur" "$DE" "$INIT")
  if [[ $new != "$cur" ]]; then
    if eselect profile list | grep -qF " $new "; then
      eselect profile set "$new"
      log "Profile: $new"
    else
      warn "Profile $new not found, keeping $cur"
    fi
  fi
}

install_packages() {
  local KPKG p
  local -a BASE D
  if [[ $KERNEL == bin ]]; then KPKG=sys-kernel/gentoo-kernel-bin; else KPKG=sys-kernel/gentoo-kernel; fi
  BASE=(sys-kernel/installkernel sys-boot/grub sys-kernel/linux-firmware "$KPKG"
        net-misc/networkmanager sys-apps/dbus sys-auth/polkit app-admin/sudo
        app-portage/gentoolkit app-shells/bash-completion)
  if [[ $BOOT_MODE == uefi ]]; then BASE+=(sys-boot/efibootmgr); fi
  if has osprober; then BASE+=(sys-boot/os-prober); fi
  if [[ $INIT == openrc ]]; then BASE+=(sys-auth/elogind net-misc/chrony); fi
  for p in $FS_PKGS; do BASE+=("$p"); done

  if [[ $INIT == systemd ]]; then systemd-machine-id-setup || true; fi
  log "Kernel, firmware, bootloader, base tools"
  emerge "${BASE[@]}"

  D=()
  case $DE in
    gnome)    D=(gnome-base/gnome gnome-base/gdm) ;;
    kde)      D=(kde-plasma/plasma-meta kde-apps/konsole kde-apps/dolphin x11-misc/sddm) ;;
    xfce)     D=(xfce-base/xfce4-meta x11-terms/xfce4-terminal x11-misc/lightdm x11-misc/lightdm-gtk-greeter) ;;
    mate)     D=(mate-base/mate x11-misc/lightdm x11-misc/lightdm-gtk-greeter) ;;
    cinnamon) D=(gnome-extra/cinnamon x11-misc/lightdm x11-misc/lightdm-gtk-greeter) ;;
  esac
  if [[ $DE != none ]]; then D+=(x11-base/xorg-server x11-drivers/xf86-input-libinput); fi
  if [[ $DE != none && $INIT == openrc ]]; then D+=(gui-libs/display-manager-init); fi
  if has audio;     then D+=(media-video/pipewire media-video/wireplumber); fi
  if has bluetooth; then D+=(net-wireless/bluez); fi
  if has bluetooth && [[ $DE == xfce || $DE == mate ]]; then D+=(net-wireless/blueman); fi
  if has wifi;      then D+=(net-wireless/wireless-regdb); fi
  if has printing;  then D+=(net-print/cups net-print/cups-filters); fi
  if has flatpak;   then D+=(sys-apps/flatpak); fi
  if ((${#D[@]} > 0)); then
    log "Desktop and extras"
    emerge "${D[@]}"
  fi
}

install_bootloader() {
  log "GRUB"
  if [[ $BOOT_MODE == uefi ]]; then
    grub-install --target=x86_64-efi --efi-directory="$EFI_MP" --bootloader-id=Gentoo \
      || { warn "No NVRAM entry possible, installing to the removable path instead"
           grub-install --target=x86_64-efi --efi-directory="$EFI_MP" --removable; }
  else
    grub-install --target=i386-pc "$BOOT_DISK"
  fi
  if has osprober; then echo 'GRUB_DISABLE_OS_PROBER=false' >> /etc/default/grub; fi
  grub-mkconfig -o /boot/grub/grub.cfg
}

configure_system() {
  local xk
  log "Timezone, locale, hostname, keymap"
  ln -sf "../usr/share/zoneinfo/$TZ_NAME" /etc/localtime
  echo "$TZ_NAME" > /etc/timezone
  printf '%s UTF-8\n' "$LOCALE" "en_US.UTF-8" | sort -u > /etc/locale.gen
  locale-gen
  printf 'LANG="%s"\nLC_COLLATE="C.UTF-8"\n' "$LOCALE" > /etc/env.d/02locale
  echo "$HOST_NAME" > /etc/hostname
  printf '127.0.0.1 localhost\n::1 localhost\n127.0.1.1 %s\n' "$HOST_NAME" > /etc/hosts
  if [[ $INIT == systemd ]]; then
    echo "LANG=$LOCALE" > /etc/locale.conf
    echo "KEYMAP=$KEYMAP" > /etc/vconsole.conf
  else
    echo "hostname=\"$HOST_NAME\"" > /etc/conf.d/hostname
    sed -i "s/^keymap=.*/keymap=\"$KEYMAP\"/" /etc/conf.d/keymaps
  fi
  if [[ $DE != none ]]; then
    xk=$(xkb_layout "$KEYMAP")
    mkdir -p /etc/X11/xorg.conf.d
    cat > /etc/X11/xorg.conf.d/00-keyboard.conf <<KBD
Section "InputClass"
    Identifier "keyboard-layout"
    MatchIsKeyboard "on"
    Option "XkbLayout" "$xk"
EndSection
KBD
  fi
  env-update

  log "User"
  useradd -m -G wheel,users,audio,video,usb,cdrom -s /bin/bash "$USERNAME"
  mkdir -p /etc/sudoers.d
  echo '%wheel ALL=(ALL:ALL) ALL' > /etc/sudoers.d/10-wheel
  chmod 440 /etc/sudoers.d/10-wheel
}

enable_services() {
  local DM=""
  log "Services"
  if [[ $INIT == systemd ]]; then systemctl preset-all --preset-mode=enable-only || true; fi
  svc NetworkManager
  if [[ $INIT == openrc ]]; then
    svc elogind boot; svc dbus; svc chronyd
  else
    systemctl enable systemd-timesyncd
  fi
  if has bluetooth; then svc bluetooth; fi
  if has printing; then
    if [[ $INIT == openrc ]]; then svc cupsd; else svc cups; fi
  fi
  case $DE in gnome) DM=gdm ;; kde) DM=sddm ;; none) DM="" ;; *) DM=lightdm ;; esac
  if [[ -n $DM ]]; then
    if [[ $INIT == openrc ]]; then
      sed -i "s/^#\?DISPLAYMANAGER=.*/DISPLAYMANAGER=\"$DM\"/" /etc/conf.d/display-manager
      rc-update add display-manager default
    else
      systemctl enable "$DM"
    fi
    if [[ $DM == lightdm && -f /etc/lightdm/lightdm.conf ]]; then
      sed -i 's/^#\?greeter-session=.*/greeter-session=lightdm-gtk-greeter/' /etc/lightdm/lightdm.conf
    fi
  fi
  if has audio; then
    if [[ $INIT == systemd ]]; then
      systemctl --global enable pipewire.socket pipewire-pulse.socket wireplumber.service \
        || warn "Could not enable PipeWire user units; run: systemctl --user enable --now pipewire pipewire-pulse wireplumber"
    elif [[ -x /usr/bin/gentoo-pipewire-launcher ]] && ! ls /etc/xdg/autostart 2>/dev/null | grep -qi pipewire; then
      mkdir -p /etc/xdg/autostart
      printf '[Desktop Entry]\nType=Application\nName=PipeWire\nExec=/usr/bin/gentoo-pipewire-launcher restart\n' \
        > /etc/xdg/autostart/gentoo-pipewire.desktop
    fi
  fi
  if has flatpak; then
    flatpak remote-add --if-not-exists flathub https://dl.flathub.org/repo/flathub.flatpakrepo \
      || warn "Flathub not added; after first boot run: flatpak remote-add --if-not-exists flathub https://dl.flathub.org/repo/flathub.flatpakrepo"
  fi
}

run_hooks() {
  local h
  for h in /root/hooks/*.sh; do
    [[ -e $h ]] || continue
    log "Hook: $(basename "$h")"
    bash "$h"
  done
}

main() {
  # shellcheck disable=SC1091
  source /root/install.conf

  log "Portage tree"
  mkdir -p /etc/portage/repos.conf
  cp /usr/share/portage/config/repos.conf /etc/portage/repos.conf/gentoo.conf
  emerge-webrsync

  set_profile
  setup_binhost
  write_make_conf
  if ! getuto; then
    warn "getuto failed, disabling binpkg signature checks"
    sed -i 's/ binpkg-request-signature//' /etc/portage/make.conf
  fi

  log "Updating @world (binhost where possible)"
  emerge --update --deep --newuse @world

  install_packages
  install_bootloader
  configure_system
  enable_services
  accept_config_updates /etc
  run_hooks
  log "Chroot stage finished"
}

if [[ ${BASH_SOURCE[0]} == "$0" ]]; then main; fi
